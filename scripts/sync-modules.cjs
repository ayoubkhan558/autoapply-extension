// Regenerate entry-point lists from the single dependency manifest.
// Run normally to write; --check exits nonzero if generated lists drift.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const modules = JSON.parse(fs.readFileSync(path.join(root, 'config/modules.json'), 'utf8'));
const check = process.argv.includes('--check');
let stale = false;
function write(file, value) {
  const target = path.join(root, file);
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === value) return;
  if (check) { console.error('Out-of-sync entry point: ' + file); stale = true; }
  else fs.writeFileSync(target, value);
}
function html(file, key) {
  let text = fs.readFileSync(path.join(root, file), 'utf8');
  const rel = (name) => path.relative(path.dirname(file), name).split(path.sep).join('/');
  const links = modules[key + 'Css'].map((f) => `  <link rel="stylesheet" href="${rel(f)}">`).join('\n');
  const scripts = modules[key + 'Js'].map((f) => `  <script src="${rel(f)}"></script>`).join('\n');
  text = text.replace(/  <!-- BEGIN MODULE STYLES -->[\s\S]*?  <!-- END MODULE STYLES -->/, `  <!-- BEGIN MODULE STYLES -->\n${links}\n  <!-- END MODULE STYLES -->`);
  text = text.replace(/  <!-- BEGIN MODULE SCRIPTS -->[\s\S]*?  <!-- END MODULE SCRIPTS -->/, `  <!-- BEGIN MODULE SCRIPTS -->\n${scripts}\n  <!-- END MODULE SCRIPTS -->`);
  write(file, text);
}
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
manifest.content_scripts[0].js = modules.contentJs;
manifest.content_scripts[0].css = modules.contentCss;
write('manifest.json', JSON.stringify(manifest, null, 2) + '\n');
write('lib/modules.js', '// Generated by scripts/sync-modules.cjs; edit config/modules.json instead.\nvar AutoApplyModules = Object.freeze(' + JSON.stringify({js: modules.contentJs, css: modules.contentCss}, null, 2) + ');\n');
let bg = fs.readFileSync(path.join(root, 'background.js'), 'utf8');
bg = bg.replace(/importScripts\([^;]*\);/, 'importScripts(' + modules.backgroundJs.map((f) => JSON.stringify(f)).join(', ') + ');');
write('background.js', bg);
html('options/options.html', 'options');
html('popup/popup.html', 'popup');
if (stale) process.exitCode = 1;
else console.log(check ? 'Module entry points are synchronized.' : 'Module entry points synchronized.');
